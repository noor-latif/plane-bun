#!/usr/bin/env bash
# Seed once; use state.sh to restore byte-identical synthetic volumes between runs.
# Run from benchmarks/p0-workload/. Local host only.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE=(docker compose -p plane-bench
  -f "$HERE/../../docker-compose.yml"
  -f "$HERE/deploy/docker-compose.bench.yml"
  --env-file "$HERE/deploy/plane-bench.env")

USER_EMAIL="bench-admin@example.invalid"
API="api"
WSROOT="$HERE/../.."

# Compose hard-requires env_file entries at the workspace root (root .env for
# plane-db/plane-mq, apps/api/.env for the api services). Generate synthetic
# bench-only files with the same values as deploy/*.env — never copy a
# canonical .env. Gitignored so they cannot reach evidence.
generate_envs() {
  # Canonical guard: never synthesize env files inside the user's canonical
  # checkout — this script is for isolated bench clones only.
  if [ "$(readlink -f "$WSROOT")" = "/home/noor/dev/apps/plane-bun" ]; then
    echo "REFUSING: WSROOT resolves to the canonical checkout; run this from a bench clone." >&2
    exit 1
  fi
  local secret
  # Reuse the existing generated SECRET_KEY when re-running on the same clone;
  # mint a fresh one only for a new bench root.
  if grep -q '^SECRET_KEY=' "$WSROOT/.env" 2>/dev/null; then
    secret="$(sed -n 's/^SECRET_KEY=//p' "$WSROOT/.env" | head -n 1)"
  else
    secret="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
  fi
  cat > "$WSROOT/.env" <<ENV
# Synthetic bench-only env, generated by benchmarks/p0-workload/seed/setup.sh.
LISTEN_HTTP_PORT=8080
LISTEN_HTTPS_PORT=8443
SITE_ADDRESS=:80
SECRET_KEY=$secret
POSTGRES_USER=bench_plane
POSTGRES_PASSWORD=bench-plane-pass-1
POSTGRES_DB=bench_plane
RABBITMQ_USER=bench_plane
RABBITMQ_PASSWORD=bench-plane-pass-2
RABBITMQ_VHOST=bench_plane
AWS_ACCESS_KEY_ID=bench-minio-key
AWS_SECRET_ACCESS_KEY=bench-minio-secret-3
AWS_S3_BUCKET_NAME=uploads
AWS_S3_ENDPOINT_URL=http://plane-bench-minio:9000
USE_MINIO=1
FILE_SIZE_LIMIT=5242880
ENV
  cat > "$WSROOT/apps/api/.env" <<ENV
# Synthetic bench-only env, generated by benchmarks/p0-workload/seed/setup.sh.
SECRET_KEY=$secret
DEBUG=0
CORS_ALLOWED_ORIGINS=http://localhost:8080,http://127.0.0.1:8080
POSTGRES_USER=bench_plane
POSTGRES_PASSWORD=bench-plane-pass-1
POSTGRES_HOST=plane-bench-db
POSTGRES_DB=bench_plane
POSTGRES_PORT=5432
DATABASE_URL=postgresql://bench_plane:bench-plane-pass-1@plane-bench-db:5432/bench_plane
REDIS_HOST=plane-bench-redis
REDIS_PORT=6379
REDIS_URL=redis://plane-bench-redis:6379/
RABBITMQ_HOST=plane-bench-mq
RABBITMQ_PORT=5672
RABBITMQ_USER=bench_plane
RABBITMQ_PASSWORD=bench-plane-pass-2
RABBITMQ_VHOST=bench_plane
AWS_ACCESS_KEY_ID=bench-minio-key
AWS_SECRET_ACCESS_KEY=bench-minio-secret-3
AWS_S3_ENDPOINT_URL=http://plane-bench-minio:9000
AWS_S3_BUCKET_NAME=uploads
USE_MINIO=1
MINIO_ENDPOINT_SSL=0
FILE_SIZE_LIMIT=5242880
SIGNED_URL_EXPIRATION=3600
WEB_URL=http://localhost:8080
GUNICORN_WORKERS=2
ADMIN_BASE_URL=http://localhost:8080
ADMIN_BASE_PATH=/god-mode
SPACE_BASE_URL=http://localhost:8080
SPACE_BASE_PATH=/spaces
APP_BASE_URL=http://localhost:8080
APP_BASE_PATH=
LIVE_BASE_URL=http://localhost:8080
LIVE_BASE_PATH=/live
LIVE_SERVER_SECRET_KEY=bench-live-secret-4
HARD_DELETE_AFTER_DAYS=60
API_KEY_RATE_LIMIT=60/minute
AUTHENTICATION_RATE_LIMIT=1000/minute
ENV
  chmod 600 "$WSROOT/.env" "$WSROOT/apps/api/.env"
}
generate_envs
bash "$HERE/seed/budget.sh" start

# Mandatory pre-build gate: fails fast on missing/blank interpolation or any
# malformed override before spending a single build minute.
"${COMPOSE[@]}" config --quiet

echo "== reusing retained images (no build or pull) =="
"${COMPOSE[@]}" config --images | while read -r image; do docker image inspect "$image" >/dev/null; done

echo "== starting infra =="
"${COMPOSE[@]}" up -d --no-build --pull never plane-db plane-redis plane-mq plane-minio

echo "== waiting for postgres =="
for _ in $(seq 1 60); do
  if "${COMPOSE[@]}" exec -T plane-db pg_isready -U bench_plane >/dev/null 2>&1; then break; fi
  sleep 2
done
"${COMPOSE[@]}" exec -T plane-db pg_isready -U bench_plane

echo "== migrations =="
"${COMPOSE[@]}" run --rm --no-deps migrator

echo "== starting api (entrypoint registers instance, creates bucket) =="
"${COMPOSE[@]}" up -d --no-build --pull never api
# proxy must be up before the health gate: the gate probes 127.0.0.1:8080,
# which is the proxy's published port, not the api's.
"${COMPOSE[@]}" up -d --no-build --pull never worker beat-worker live web admin space proxy

echo "== waiting for api health (through proxy) =="
for i in $(seq 1 90); do
  if curl -fsS http://127.0.0.1:8080/auth/get-csrf-token/ >/dev/null 2>&1; then break; fi
  sleep 2
done
curl -fsS http://127.0.0.1:8080/auth/get-csrf-token/ >/dev/null

echo "== seeding: admin user + instance setup flag =="
"${COMPOSE[@]}" exec -T "$API" python manage.py shell <<PY
import secrets
from django.conf import settings
from django.contrib.auth.hashers import make_password
from plane.db.models import User, Profile
from plane.license.models import Instance

inst = Instance.objects.first()
assert inst is not None, "instance not registered; api entrypoint failed"
admin = User.objects.filter(email="${USER_EMAIL}").first()
if admin is None:
    password = "Bench-" + secrets.token_urlsafe(12)
    admin = User.objects.create(
        email="${USER_EMAIL}",
        username=secrets.token_hex(8),
        first_name="Bench",
        last_name="Admin",
        password=make_password(password),
        is_password_autoset=True,
        is_active=True,
    )
    Profile.objects.create(user=admin)
    admin.is_active = True
    admin.last_active = __import__("django.utils.timezone", fromlist=["now"]).now()
    admin.save()
    with open("/tmp/bench_admin_password", "w") as f:
        f.write(password)
    print("PASSWORD written to /tmp/bench_admin_password")
else:
    print("PASSWORD already exists")
if not inst.is_setup_done:
    inst.is_setup_done = True
    inst.save(update_fields=["is_setup_done", "instance_name"])
    print("SETUP_DONE")
PY

echo "== starting worker + beat + front =="
"${COMPOSE[@]}" up -d --no-build --pull never worker beat-worker live web admin space proxy

echo "== seeding: dataset (create_dummy_data is an IN-PROCESS direct call — setup only, not queue evidence; broker durability is proven by the runner's issue_activity.delay traffic) =="
GENERATED="$("${COMPOSE[@]}" exec -T "$API" python manage.py shell <<PY
import json
from django.utils import timezone
from plane.db.models import User, Profile, Workspace, WorkspaceMember, Project, ProjectMember, Issue, Page
from plane.bgtasks.dummy_data_task import create_dummy_data

admin = User.objects.get(email="${USER_EMAIL}")
ws = Workspace.objects.filter(slug="bench").first()
if ws is None:
    ws = Workspace.objects.create(slug="bench", name="Bench Workspace", owner=admin)
    WorkspaceMember.objects.create(workspace=ws, member=admin, role=20)
project = Project.objects.filter(workspace=ws).first()
if project is None:
    # members MUST include the admin (upstream task samples ProjectMember for
    # assignees) and module_count must be >= 6 (create_module_issues draws
    # random.sample(modules, randint(0, 5)) per issue — k>len(modules) raises;
    # reproducible with the baseline task, not a bench bug);
    # create_dummy_data generates a RANDOM identifier — never assume one.
    create_dummy_data(
        slug="bench",
        email="${USER_EMAIL}",
        members=["${USER_EMAIL}"],
        issue_count=400,
        cycle_count=0,
        module_count=6,
        pages_count=12,
        intake_issue_count=0,
    )
    project = Project.objects.filter(workspace=ws).first()
    Issue.objects.filter(project=project).update(archived_at=None)
password = open("/tmp/bench_admin_password").read().strip()
users = []
for index in range(20):
    email = "${USER_EMAIL}" if index == 0 else f"bench-user-{index}@example.invalid"
    user, created = User.objects.get_or_create(
        email=email,
        defaults={"username": f"bench-user-{index}", "first_name": "Bench", "last_name": str(index),
                  "is_active": True, "is_password_autoset": True},
    )
    if created:
        user.set_password(password)
        user.save()
        Profile.objects.get_or_create(user=user)
    WorkspaceMember.objects.get_or_create(workspace=ws, member=user, defaults={"role": 20})
    ProjectMember.objects.get_or_create(workspace=ws, project=project, member=user, defaults={"role": 20})
    users.append({"email": email, "password": password})
# Five users collaborate on a public project page; private-page policy stays intact.
collaboration_page = Page.objects.filter(projects=project).order_by("id").first()
collaboration_page.access = Page.PUBLIC_ACCESS
collaboration_page.save(update_fields=["access"])
info = {
    "workspace_slug": ws.slug,
    "project_identifier": project.identifier,
    "project_id": str(project.id),
    "issue_count": Issue.objects.filter(project=project).count(),
    "issue_ids": [str(value) for value in Issue.objects.filter(project=project).order_by("id").values_list("id", flat=True)[:100]],
    "page_ids": [str(p.id) for p in Page.objects.filter(projects=project).order_by("id")[:12]],
    "seeded_at": timezone.now().isoformat(),
}
print(json.dumps({"dataset": info, "users": users}))
PY
)"
DATASET="$(echo "$GENERATED" | tail -n 1)"
echo "$DATASET" | python3 -c 'import json,sys; json.loads(sys.stdin.read())' >/dev/null

# extract the generated password recorded during seeding (grep the exact
# value line — manage.py shell prints chatter like "N objects imported" that
# `tail -n 1` once mistook for the password)
PASSWORD="$("${COMPOSE[@]}" exec -T "$API" python manage.py shell -c \
  "print(open('/tmp/bench_admin_password').read().strip())" | grep -E '^Bench-' | tail -n 1)"

python3 - "$DATASET" "$PASSWORD" > "$HERE/seed/user.json" <<PY
import json, sys
data = json.loads(sys.argv[1])
json.dump({"email": "${USER_EMAIL}", "password": sys.argv[2], **data}, sys.stdout, indent=1)
PY
chmod 600 "$HERE/seed/user.json"

echo "== smoke: sign-in through proxy =="
PASSWORD="$(python3 - "$HERE/seed/user.json" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
print(d["password"])
PY
)"
COOKIE_JAR="$(mktemp)"
curl -fsS -c "$COOKIE_JAR" http://127.0.0.1:8080/auth/get-csrf-token/ >/dev/null
CSRF="$(python3 -c 'import re,sys; print(re.search(r"csrftoken\s+(\S+)", open(sys.argv[1]).read()).group(1))' "$COOKIE_JAR")"
curl -fsS -b "$COOKIE_JAR" -H "Origin: http://localhost:8080" -H "X-CSRFToken: $CSRF" \
  --data-urlencode "email=$USER_EMAIL" --data-urlencode "password=$PASSWORD" \
  http://127.0.0.1:8080/auth/sign-in/ -o /dev/null -w '%{http_code}\n' | grep -q 302

echo "setup complete: seed/user.json written (gitignored)"
